/** The placeholder token for a chapter and section, e.g. {{p:23:When someone repeats your idea in a meeting}}. */
export function pageToken(ch: number, section: string): string {
  return `{{p:${ch}:${section}}}`;
}

function lookup(ch: number, section: string): number | undefined {
  return pageMap[pageToken(ch, section)];
}

/** Long form for running text: "Chapter 23, page 112", or "Chapter 23" until the page is known. */
export function pageRef(ch: number, section: string): string {
  const p = lookup(ch, section);
  return p ? `Chapter ${ch}, page ${p}` : `Chapter ${ch}`;
}

/** Short form for the page-number column: "p. 112", or "Ch. 23" until the page is known. */
export function pageRefShort(ch: number, section: string): string {
  const p = lookup(ch, section);
  return p ? `p. ${p}` : `Ch. ${ch}`;
}

/** True once at least one printed page number has been filled in. */
export const HAS_PAGE_NUMBERS = Object.keys(pageMap).length > 0;
