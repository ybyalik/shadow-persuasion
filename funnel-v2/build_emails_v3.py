"""Turns the NEW-edition free-chapter email sequence into a TypeScript module.

Run from the repo root after editing funnel-v2/emails/free-chapter-sequence-v3.md:
    python3 funnel-v2/build_emails_v3.py
Writes lib/sp2/emails-v3.generated.ts (do not edit that file by hand).

The site sends these instead of lib/sp2/content.generated.ts's emails only when
NEXT_PUBLIC_BOOK_EDITION=v3 (lib/sp2/server.ts, lib/edition.ts). This script never
touches content.generated.ts, which build_web_content.py owns.
Needs pandoc (brew install pandoc). Reads and writes local files only.
"""
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from build_web_content import md_to_html, md_to_text  # noqa: E402  same converters as the v2 emails

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "funnel-v2" / "emails" / "free-chapter-sequence-v3.md"
OUT = ROOT / "lib" / "sp2" / "emails-v3.generated.ts"


def parse_emails():
    src = SRC.read_text()
    blocks = re.split(r"^## Email (\d+) \(Day (\d+)\)\s*$", src, flags=re.M)
    emails = []
    for i in range(1, len(blocks), 3):
        num, day, body = int(blocks[i]), int(blocks[i + 1]), blocks[i + 2]
        body = body.split("\n---", 1)[0].strip()
        subject = re.search(r"^\*\*Subject:\*\* (.+)$", body, flags=re.M).group(1).strip()
        preview = re.search(r"^\*\*Preview:\*\* (.+)$", body, flags=re.M).group(1).strip()
        content = re.sub(r"^\*\*(Subject|Preview):\*\* .+$\n?", "", body, flags=re.M).strip()
        assert "—" not in content + subject + preview, f"em-dash in email {num}"
        emails.append({
            "number": num, "day": day, "subject": subject, "preview": preview,
            # pandoc URL-encodes the braces in link targets ("%7B%7Bbook_link%7D%7D"), which the
            # sender's {{placeholder}} fill does not match, so put the braces back.
            "html": re.sub(r"%7B%7B(\w+)%7D%7D", r"{{\1}}", md_to_html(content)), "text": md_to_text(content),
        })
    assert len(emails) == 20, f"expected 20 emails, found {len(emails)}"
    assert [e["number"] for e in emails] == list(range(1, 21)), "emails must be numbered 1 to 20 in order"
    return emails


def main():
    emails = parse_emails()
    OUT.write_text(
        "// Generated by funnel-v2/build_emails_v3.py from funnel-v2/emails/free-chapter-sequence-v3.md. Do not edit by hand.\n"
        "// Sent only when NEXT_PUBLIC_BOOK_EDITION=v3 (see lib/edition.ts).\n\n"
        "import type { Sp2Email } from './content.generated';\n\n"
        f"export const SP2_EMAILS_V3: Sp2Email[] = {json.dumps(emails, indent=2)};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(emails)} emails)")


if __name__ == "__main__":
    main()
