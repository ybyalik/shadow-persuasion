"""Turns the v2 manuscript + email sequence into a TypeScript module the site imports.

Run from the repo root after editing funnel-v2/chapters/ch-01*.md or funnel-v2/emails/*.md:
    python3 funnel-v2/build_web_content.py
Writes lib/sp2/content.generated.ts (do not edit that file by hand).
"""
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
V2 = ROOT / "funnel-v2"
OUT = ROOT / "lib" / "sp2" / "content.generated.ts"


def md_to_html(md: str) -> str:
    return subprocess.run(
        ["pandoc", "-f", "markdown", "-t", "html", "--wrap=none"],
        input=md, capture_output=True, text=True, check=True,
    ).stdout.strip()


def md_to_text(md: str) -> str:
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1: \2", md)
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"\1", text)
    text = re.sub(r"^> ?", "", text, flags=re.M)
    return text.strip()


def parse_emails():
    src = (V2 / "emails" / "free-chapter-sequence.md").read_text()
    blocks = re.split(r"^## Email (\d+) \(Day (\d+)\)\s*$", src, flags=re.M)
    emails = []
    for i in range(1, len(blocks), 3):
        num, day, body = int(blocks[i]), int(blocks[i + 1]), blocks[i + 2]
        body = body.split("\n---", 1)[0].strip()
        subject = re.search(r"^\*\*Subject:\*\* (.+)$", body, flags=re.M).group(1).strip()
        preview = re.search(r"^\*\*Preview:\*\* (.+)$", body, flags=re.M).group(1).strip()
        content = re.sub(r"^\*\*(Subject|Preview):\*\* .+$\n?", "", body, flags=re.M).strip()
        emails.append({
            "number": num,
            "day": day,
            "subject": subject,
            "preview": preview,
            "html": md_to_html(content),
            "text": md_to_text(content),
        })
    assert len(emails) == 20, f"expected 20 emails, found {len(emails)}"
    return emails


def chapter_one():
    md = next((V2 / "chapters").glob("ch-01-*.md")).read_text()
    # The page renders its own title and call to action, so drop the H1 and the free-chapter footer.
    md = re.sub(r"^# Part .+\n+", "", md, count=1)
    md = re.sub(r"^# .+\n", "", md, count=1)
    md = md.split("\n---\n\n*End of free chapter.*", 1)[0]
    return md_to_html(md)


def main():
    emails = parse_emails()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by funnel-v2/build_web_content.py. Do not edit by hand.\n\n"
        "export type Sp2Email = { number: number; day: number; subject: string; preview: string; html: string; text: string };\n\n"
        f"export const CHAPTER_ONE_HTML: string = {json.dumps(chapter_one())};\n\n"
        f"export const SP2_EMAILS: Sp2Email[] = {json.dumps(emails, indent=2)};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(emails)} emails)")


if __name__ == "__main__":
    main()
